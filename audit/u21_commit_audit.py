"""
Before the wiring pass: every number commit 6b353ed put into the paper, with its
owner and whether that owner changed in the same commit.

WHY THIS RUNS FIRST, and the reason is about wiring rather than about numbers.
A wrong LITERAL is findable, because nothing vouches for it. A wrong number
WIRED to a macro and generated by the script that produced it is self-consistent,
passes its own guard, and is reported as "ARTEFACTS MATCH THE CODE". **Wiring
makes an error permanent and invisible at the same time**, so anything suspect
must be settled before promotion rather than after.

WHY THIS COMMIT. 6b353ed is not merely the commit that coarsened `d6`'s tau grid
(R138). In one commit it:

  created  audit/PHASE2D_FINDINGS.md, d0b_proposition2.py, d0c_mechanism.py,
           d0d_generalised_E.py, d11_priorfree.py, d12_minimal_footing.py,
           d9_loadvariation.py
  changed  audit/d6_regimes.py (+34), src/design/run.py (+51)
  edited   paper/sections/06_excitation.tex (+249), 07_design.tex (+121)
  regenerated  results/tables/tab_D_designs.tex, results/figures/fig_D3_decision.pdf

**Eight scripts and 370 lines of paper text in one commit.** And R138 established
that of the two threshold numbers the paper took from it, ONE tracked the
generator change in that commit and the other did not: `+0.07` is a faithful
reading of `d6` AFTER the coarsening, while `-0.39` is a carryover from before
it. So the commit demonstrably contains numbers on both sides of a generator
change, which is exactly the condition that makes a per-number audit necessary.

VERDICTS, per distinct literal the commit ADDED.
  GONE       not in the paper today. Superseded already; no action.
  WIRED      now carried by a `\\num{}` macro. Already has a generator.
  SUSPECT    a candidate owner exists AND that owner changed in 6b353ed. Must be
             re-derived before anything near it is wired.
  OWNED      a candidate owner exists and it did not change in 6b353ed.
  NO-OWNER   no script in the repository contains it. A prose literal with no
             generator, which cannot be wired without deriving it first.
  STRUCTURAL an index, exponent, count or reference rather than a result.

A candidate owner is evidence and not proof: the literal appearing in a script
means that script mentions the value, not necessarily that it computes it. The
point of the column is to say which numbers need a human, and how urgently.

Nothing here records an expected result in advance.

Run:  python audit/u21_commit_audit.py
"""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
COMMIT = "6b353ed"
SECTIONS = ["paper/sections/06_excitation.tex", "paper/sections/07_design.tex"]


def sh(*args):
    return subprocess.run(args, cwd=ROOT, capture_output=True,
                          text=True).stdout


def changed_in_commit():
    out = sh("git", "show", "--name-only", "--format=", COMMIT)
    return {l.strip() for l in out.splitlines() if l.strip()}


def added_lines():
    d = sh("git", "diff", f"{COMMIT}^", COMMIT, "--", *SECTIONS)
    return [l[1:] for l in d.splitlines()
            if l.startswith("+") and not l.startswith("+++")]


#: a result-shaped number: a decimal, or scientific notation
RESULT = re.compile(r"(?<![\d.])(\d+\.\d+|\d+(?:\.\d+)?\s*\\times\s*10\^\{?-?\d+\}?)")
#: bare small integers we classify as structural unless they carry a unit or %
INT = re.compile(r"(?<![\d.])(\d+)(?![\d.])")


def literals(line):
    """Result-shaped numbers on a line, plus integers marked structural."""
    got = []
    for m in RESULT.finditer(line):
        got.append((re.sub(r"\s+", "", m.group(1)), False))
    for m in INT.finditer(line):
        v = m.group(1)
        if any(v == g[0].split(".")[0] and not g[1] for g in got):
            continue
        #  an integer is a result only if it is a percentage or a count the
        #  prose treats as measured; everything else is an index or a label
        tail = line[m.end():m.end() + 3]
        got.append((v, not tail.startswith("\\%")))
    return got


def owners(val):
    """Scripts mentioning this literal. Evidence of an owner, not proof."""
    out = sh("grep", "-rl", "--include=*.py", val, "audit", "src")
    return sorted(l.strip() for l in out.splitlines() if l.strip())


def in_paper_today(val):
    out = sh("grep", "-rl", val, *SECTIONS)
    return bool(out.strip())


def wired_today(val):
    """Is a macro now standing where this literal was? Approximate."""
    for s in SECTIONS:
        txt = (ROOT / s).read_text(errors="replace")
        if val in txt:
            return False
    #  absent as a literal; check whether the section gained macros at all
    return True


if __name__ == "__main__":
    ch = changed_in_commit()
    lines = added_lines()
    print("=" * 100)
    print(f"EVERY NUMBER {COMMIT} ADDED TO THE PAPER, with its owner and whether "
          f"that owner changed in the same commit")
    print("=" * 100)
    print(f"\n  files that commit changed: {len(ch)}")
    for f in sorted(ch):
        print(f"    {'CHANGED  ' if f.endswith('.py') else '         '}{f}")
    print(f"\n  added lines in the two sections: {len(lines)}")

    seen, rows = {}, []
    for ln in lines:
        for val, structural in literals(ln):
            if val in seen:
                continue
            seen[val] = ln.strip()
            rows.append((val, structural, ln.strip()))

    tally = {}
    out_rows = []
    for val, structural, ctx in rows:
        here = in_paper_today(val)
        own = owners(val)
        own_changed = [o for o in own if o in ch]
        if not here:
            v = "GONE"
        elif structural:
            v = "STRUCTURAL"
        elif own_changed:
            v = "SUSPECT"
        elif own:
            v = "OWNED"
        else:
            v = "NO-OWNER"
        tally[v] = tally.get(v, 0) + 1
        out_rows.append((v, val, own_changed or own, ctx))

    order = ["SUSPECT", "NO-OWNER", "OWNED", "GONE", "STRUCTURAL"]
    for v in order:
        sel = [r for r in out_rows if r[0] == v]
        if not sel:
            continue
        print()
        print("=" * 100)
        print(f"{v}  ({len(sel)})")
        print("=" * 100)
        for _, val, own, ctx in sorted(sel, key=lambda r: r[1]):
            o = ", ".join(Path(x).name for x in own[:3]) or "-"
            print(f"  {val:>18}   {o:<52} {ctx[:60]}")

    print()
    print("=" * 100)
    print("  " + "   ".join(f"{k} {tally.get(k, 0)}" for k in order))
    print("=" * 100)
    print("""
  SUSPECT is the column that blocks the wiring pass: a candidate owner exists
  and that owner changed in this very commit, so the number may be on either
  side of the change, as R138 showed for the two threshold values. NO-OWNER
  blocks it differently: there is no generator to wire to, so promoting such a
  number means deriving it first. Neither is cleared by this script.""")
    sys.exit(0)
