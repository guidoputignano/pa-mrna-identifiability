"""
The generator for Phase 11's numbers: it COMPUTES them and emits them as
`\\num{}` macros, so the guard has something real to check.

WHY THIS FILE COMPUTES RATHER THAN TABULATES. R141 found
`06_excitation.tex:103`'s `0.587 -> 0.209` traced only to a sentence in
`d0c_mechanism.py`'s docstring, which the script does not compute. A generator
that hardcoded its values would be that failure in a new guise, and worse,
because `check_artefacts.py` would then report `ARTEFACTS MATCH THE CODE` for
numbers typed in by hand. **Every value below is obtained by calling the function
that owns it.**

THE FOOTING IS STATED IN EVERY DECLARATION, per R145. The recommended design's
objects are computed on the paper's **committed post-dose footing**, obtained by
building the record with `src/design/run.py`'s own `design_record` rather than
rebuilding the dose train, because a ratio formed across two footings is the
defect R142 caught.

NAMES CARRY THEIR DESIGN, per the author's ruling that wiring freezes names as
much as values. `profile_recommended` is the 25-monthly design's and
`profile_tier1` is the 118-draw design's; they are 0.2005 and 0.2268 and a shared
prefix invited conflating them.

WHAT IS DELIBERATELY NOT HERE.
  The breath group, whose values are row-selections from CV-indexed tables and
  so need their row named before they can be promoted (R143).
  `rho_above_fail_lo` and `rho_above_fail_hi`, dropped because the spread they
  report is ZERO across all eight seeds, so the macro renders "100.0 to 100.0"
  and destroys the finding it was meant to protect. The prose clause "with no
  seed-to-seed variation" is restored instead (R143).
  `06_excitation.tex:103`'s pair, which has no generator at all (R141).

SLOW. The frontier bisects over 24 seeds at three capacities and the profile
searches a likelihood at each seed, so this is minutes rather than seconds, in
the same class as `k4_admissibility.py` and `d13_decision_therapy.py`.

Run:  python audit/u23_wire_phase11.py
"""
