#: the value PART A of u22 must reproduce for the footing to be the paper's
SD_COMMITTED = 0.1699


def frontier_group():
    """The k_e requirement frontier, from u9, which owns it."""
    out = {}
    for theta, tag in ((3000.0, "3000"), (600.0, "600"), (300.0, "300")):
        s, _ = U9.frontier(theta, U9.TIER1_N, U9.PUBLISHED_KAPPA_CV)
        if s is None or not np.isfinite(s):
            continue
        out[f"ke_frontier_{tag}_pct"] = 100.0 * float(s)
        out[f"ke_frontier_{tag}_factor"] = float(np.exp(s))
    out["ke_prior_pct"] = 100.0 * float(KE_PRIOR_LOG)
    return out


def objects_group():
    """
    The marginal, profile and simulated spread at two designs, all on the
    paper's committed post-dose footing.

    The anchor is checked here rather than trusted: if the marginal does not
    reproduce the committed 0.1699, this function raises rather than emitting
    numbers on a footing that is not the paper's.
    """
    sig = U22.sigma_of(P.theta)
    marg, los, his = [], [], []
    for s in D.SEEDS:
        lv, inc, Ls = U22.build(U22.MONTHLY, s)
        marg.append(U22.marginal(P.theta, lv, inc, sig))
        a, b = U22.profile(P.theta, lv, inc, Ls, sig)
        los.append(a)
        his.append(b)
    m = float(np.median([x for x in marg if np.isfinite(x)]))
    if abs(m - SD_COMMITTED) > 5e-4:
        raise AssertionError(
            f"footing not matched: marginal {m:.4f} against the committed "
            f"{SD_COMMITTED}. Nothing is emitted, because a number on the "
            f"wrong footing that passes the guard is worse than no number.")
    lo, hi = float(np.median(los)), float(np.median(his))
    prof = 0.5 * (lo + hi)

    kcv = 0.1402
    t1m, t1p = [], []
    for s in D.SEEDS:
        lv, inc, Ls = U22.build(U22.TIER1, s)
        t1m.append(U22.marginal(P.theta, lv, inc, sig, kappa_cv=kcv))
        a, b = U22.profile(P.theta, lv, inc, Ls, sig, kappa_cv=kcv)
        t1p.append(0.5 * (a + b))
    tm = float(np.median([x for x in t1m if np.isfinite(x)]))
    tp = float(np.median(t1p))

    #  `m` is NOT emitted. It is the same quantity as the existing
    #  `sd_monthly` (0.1699, generated by src/design/run.py) on the same
    #  footing, and two keys for one value can diverge while the guard, which
    #  checks keys rather than values, reports a match. Its role here is the
    #  assertion above: it proves the footing, and the paper keeps quoting
    #  `sd_monthly`.
    rob, sd = U22.sim_spreads()
    return {
        "sim_spread_recommended": sd,
        "sim_spread_robust_recommended": rob,
        "profile_recommended": prof,
        "profile_lo_recommended": lo,
        "profile_hi_recommended": hi,
        "profile_asym_recommended": hi / lo,
        "object_spread_recommended_pct": 100.0 * (prof / m - 1.0),
        "sd_tier1_with_kappa": tm,
        "profile_tier1": tp,
        "profile_gap_tier1_pct": 100.0 * (tp / tm - 1.0),
    }


def quad_group():
    """
    The prior width at which the profile's asymmetry disappears.

    Defined as the LOOSEST swept width whose right/left half-width ratio is
    within 0.005 of one, because "disappears" needs a threshold and leaving it
    implicit is how a macro acquires a meaning nobody chose.

    THE DIRECTION MATTERS AND THE FIRST VERSION HAD IT WRONG. Asymmetry falls
    as the prior narrows, so the widths at which it is closed form a tail:
    0.20 is not closed (ratio 0.973), 0.10 and 0.05 are. The useful statement
    is the LOOSEST prior that suffices, 0.10, since that is what a measurement
    would have to reach. The first version overwrote its candidate on every
    match while descending and so returned the TIGHTEST, 0.05, which says a
    measurement must be twice as good as it needs to be. Taking the first
    match in descending order is the fix, and this is the fourth defect of
    this kind found in my own code in one sitting, every one of which the
    guard would have certified.
    """
    seeds = range(8)
    for w in (0.80, 0.40, 0.20, 0.10, 0.05):
        r = []
        for s in seeds:
            m, inc, Ls = U12.record(P.theta, 25, s)
            a, b = U12.profile_halfwidths(P.theta, m, inc, Ls,
                                          U12.sigma_of(P.theta), w)
            r.append(b / a)
        if abs(float(np.median(r)) - 1.0) <= 5e-3:
            return {"quad_width": w}
    return {"quad_width": float("nan")}


if __name__ == "__main__":
    N = {}
    print("  frontier group, from u9 ...")
    N.update(frontier_group())
    print("  objects group, on the committed post-dose footing ...")
    N.update(objects_group())
    print("  the width at which the asymmetry closes ...")
    N.update(quad_group())
    #  (g4)'s margin target, DERIVED rather than asserted. The first version
    #  hardcoded 0.17 with a comment saying it was a decision, which is the
    #  rho case again: a macro asserts that a number came from the code, so a
    #  judgement emitted by a generator is a false claim about its own
    #  provenance. It is not a bare recommendation: the gate is 0.20 on the
    #  marginal, and stating it against the profile means deflating it by the
    #  measured object spread, which is where 0.17 comes from. Now it tracks
    #  the spread instead of being pinned beside it.
    GATE = 0.20
    N["margin_target"] = GATE / (1.0 + N["object_spread_recommended_pct"] / 100.0)

    fmt = {k: "{:.2f}" for k in N if k.endswith("_pct")}
    fmt.update({k: "{:.4f}" for k in N if k.startswith(("sd_", "profile_"))
                and not k.endswith("_pct")})
    fmt.update({"profile_asym_recommended": "{:.3f}",
                "ke_frontier_3000_factor": "{:.3f}",
                "ke_frontier_600_factor": "{:.3f}",
                "ke_frontier_300_factor": "{:.3f}",
                "quad_width": "{:.2f}",
                "margin_target": "{:.2f}",
                "ke_prior_pct": "{:.0f}"})
    write_numbers("frontier", N, fmt)
    print()
    for k in sorted(N):
        print(f"    {k:<34} {N[k]}")
