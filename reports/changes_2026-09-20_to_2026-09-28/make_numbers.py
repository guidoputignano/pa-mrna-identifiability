def put(key, value, source):
    if key in VALUES and VALUES[key] != value:
        raise SystemExit(f"{key}: two values, {VALUES[key]} and {value}")
    VALUES[key], SOURCES[key] = value, source


# ---------------------------------------------------------------- generated
NUM_RE = re.compile(r"\\csname paper@num@([A-Za-z0-9_]+)\\endcsname\{([^}]*)\}")


def load_generated(rev, prefix):
    files = git("ls-tree", "--name-only", rev, "results/numbers/").split()
    for f in files:
        if not f.endswith(".tex"):
            continue
        text = git("show", f"{rev}:{f}")
        gen = re.search(r"generated by (\S+)", text)
        if gen and prefix == "new":
            put(f"gen.{Path(f).stem}", gen.group(1).replace("_", "\\_"), f"{f}:1 @ {rev[:7]}")
        for i, line in enumerate(text.splitlines(), 1):
            for k, v in NUM_RE.findall(line):
                put(f"{prefix}.{k}", v, f"{f}:{i} @ {rev[:7]}")


# ---------------------------------------------------------------- literals
def source(rev, path):
    return git("show", f"{rev}:{path}")


def lit(prefix, rev, key, path, pattern):
    text = source(rev, path)
    m = re.search(pattern, text, flags=re.S)
    if m is None:
        FAILED.append(f"{prefix}.{key}: /{pattern}/ not found in {path} @ {rev[:7]}")
        return
    if m.groupdict():
        for name, val in m.groupdict().items():
            line = text.count("\n", 0, m.start(name)) + 1
            put(f"{prefix}.{key}_{name}", val, f"{path}:{line} @ {rev[:7]}")
        return
    group = next(i for i in range(1, (m.lastindex or 1) + 1) if m.group(i) is not None)
    line = text.count("\n", 0, m.start(group)) + 1
    put(f"{prefix}.{key}", m.group(group), f"{path}:{line} @ {rev[:7]}")


